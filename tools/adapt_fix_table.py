#!/usr/bin/env python3
"""Before/after tables of the particle-management rerun (HyperCloudCore main vs claude/adaptivity-conservation).

    python3 tools/adapt_fix_table.py results/adapt_fix/all.log > reports/2026-10-28-adapt-fix-tables.md

Reads the RESULT lines written by tools/adapt_study.jl through the local batch (prefixed with env=env_main|env_fix)
and prints one Markdown table per case: relative mass change at t_end with adaptivity on (main, fix) and off,
the part of it caused by re-estimating the volumes after adaptation calls (rel_revolume_sum), the largest
mass change of a single adaptation call (max_abs_remap), and the particle counts.
"""
import re
import sys
from collections import defaultdict

runs = defaultdict(dict)          # (env, tag) -> fields
for line in open(sys.argv[1]):
    if not line.startswith("RESULT"):
        continue
    f = dict(re.findall(r"(\w+)=(\S+)", line))
    key = (f.get("env"), f.get("tag"))
    runs[key].update(f)

def first(v):
    return float(v.split(",")[0]) if v else float("nan")

cases = defaultdict(lambda: defaultdict(dict))  # case_K_vol -> N -> column -> fields
for (env, tag), f in runs.items():
    m = re.match(r"(\w+?)_K(\d)_(\w+?)_(on|off)_N(\d+)$", tag or "")
    if not m:
        continue
    case, K, vol, adapt, N = m.groups()
    cases[f"{case}, K = {K}, {vol} volumes"][int(N)][f"{env}_{adapt}"] = f

def fmt(x):
    return "—" if x != x else f"{x:+.2e}"

print("# 2026-10-28: Particle management, main vs fix: full tables\n")
print("Generated by `python3 tools/adapt_fix_table.py results/adapt_fix/all.log` from the local batch "
      "`tools/adapt_fix_batch.sh` (HyperCloudCore main `2fe8b46` vs `claude/adaptivity-conservation` `fad1503`). "
      "Relative mass change at t_end; \"re-volume part\" = `rel_revolume_sum`; \"max call\" = largest absolute mass "
      "change of one adaptation call. Discussion: `reports/2026-10-28-particle-management-fixes.md`.")

for name in sorted(cases):
    print(f"\n### {name}\n")
    print("| N | mass, adapt off | mass, on (main) | mass, on (fix) | re-volume part (main) | re-volume part (fix) "
          "| max call (main) | max call (fix) | particles end (main / fix) | status |")
    print("|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--|")
    for N in sorted(cases[name]):
        c = cases[name][N]
        off, mo, fx = c.get("env_fix_off", {}), c.get("env_main_on", {}), c.get("env_fix_on", {})
        status = ",".join(sorted({x.get("status", "?") for x in (off, mo, fx) if x}))
        nend = lambda x: x.get("N", "?").split("->")[-1] if x else "—"
        print(f"| {N} | {fmt(first(off.get('rel_mass_change')))} | {fmt(first(mo.get('rel_mass_change')))} "
              f"| {fmt(first(fx.get('rel_mass_change')))} | {fmt(first(mo.get('rel_revolume_sum')))} "
              f"| {fmt(first(fx.get('rel_revolume_sum')))} | {float(mo.get('max_abs_remap', 'nan')):.1e} "
              f"| {float(fx.get('max_abs_remap', 'nan')):.1e} | {nend(mo)} / {nend(fx)} | {status} |")
